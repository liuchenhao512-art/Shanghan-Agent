let streamingCalls = 0;
const mock = http.createServer(async (req, res) => {
  let raw = ''; for await (const chunk of req) raw += chunk;
  const input = JSON.parse(raw);
  if (input.stream) {
    streamingCalls++;
    res.writeHead(200, { 'Content-Type': 'text/event-stream' });
    res.end('data: ' + JSON.stringify({ choices: [{ delta: { content: '【程序验证导读】此内容仅用于测试流式传输，不是学术结论。' } }] }) + '\n\ndata: [DONE]\n\n'); return;
  }
  let output = '连接成功（程序验证服务）';
  try {
    const query = JSON.parse(input.messages.at(-1).content);
    if (query.conversation) conversations.push(query.conversation);
    const rag = require('./qa-rag.cjs').modelReply(query);
    if (rag) output = JSON.stringify(rag);
    else if (query.evidence) output = JSON.stringify({ [query.question.includes('接着') ? 'answer' : 'comparison']: [{ text: query.question.includes('接着') ? '接着上一轮的问题，回到原文核对“汗出恶风”。这是连续追问的程序验证，不作为学术结论。' : '程序验证：已检索并读取所选资料，不作为学术结论。', citations: [{ evidence_id: query.evidence[0].evidence_id, quote: '汗出恶风' }] }], consensus: [], differences: [], gaps: ['这是确定性程序测试，真实学术研读需另行验收。'] });
    else if (query.search_results?.length) output = JSON.stringify({ queries: [], read_ids: [query.search_results.find(x => x.snippet.includes('汗出恶风')).id], finish: true });
    else output = JSON.stringify({ queries: ['太阳'], read_ids: [], finish: false });
  } catch {}
  res.writeHead(200, { 'Content-Type': 'application/json' });
  res.end(JSON.stringify({ choices: [{ message: { content: output } }], usage: { prompt_tokens: 10, completion_tokens: 10 } }));
});
