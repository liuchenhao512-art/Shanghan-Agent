async function screenshot(app, filename) {
  // 隐藏的桌面测试窗口使用原生捕获，避免 Chromium 等待不可见帧而超时。
  console.log('保存界面截图：' + path.basename(filename));
  let captureTimeout;
  const encoded = await Promise.race([app.evaluate(async ({ BrowserWindow }) => {
    const window = BrowserWindow.getAllWindows().find(w => w.webContents.getURL() === 'app://shanghan/') || BrowserWindow.getAllWindows()[0];
    window.webContents.invalidate();
    return (await window.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG().toString('base64');
  }), new Promise(resolve => { captureTimeout = setTimeout(() => resolve(null), 10000); })]);
  clearTimeout(captureTimeout);
  if (!encoded) { console.log('隐藏窗口未返回截图，继续功能验证；界面另以浏览器截图核对。'); return; }
  assert.ok(encoded.length > 1000);
  await fs.writeFile(filename, Buffer.from(encoded, 'base64'));
}
